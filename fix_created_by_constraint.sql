-- Check for the problematic created_by_id constraint
SELECT
    TC.CONSTRAINT_NAME,
    TC.TABLE_NAME,
    KCU.COLUMN_NAME,
    CCU.TABLE_NAME AS FOREIGN_TABLE_NAME,
    CCU.COLUMN_NAME AS FOREIGN_COLUMN_NAME
FROM
    INFORMATION_SCHEMA.TABLE_CONSTRAINTS AS TC
    JOIN INFORMATION_SCHEMA.KEY_COLUMN_USAGE AS KCU
    ON TC.CONSTRAINT_NAME = KCU.CONSTRAINT_NAME
    AND TC.TABLE_SCHEMA = KCU.TABLE_SCHEMA
    JOIN INFORMATION_SCHEMA.CONSTRAINT_COLUMN_USAGE AS CCU
    ON CCU.CONSTRAINT_NAME = TC.CONSTRAINT_NAME
    AND CCU.TABLE_SCHEMA = TC.TABLE_SCHEMA
WHERE
    TC.CONSTRAINT_TYPE = 'FOREIGN KEY'
    AND TC.TABLE_NAME = 'issues'
    AND (KCU.COLUMN_NAME = 'created_by_id'
    OR TC.CONSTRAINT_NAME LIKE '%created_by%');

-- Drop the problematic created_by_id constraint if it exists
DO $$

BEGIN
    IF EXISTS (
        SELECT
            1
        FROM
            INFORMATION_SCHEMA.TABLE_CONSTRAINTS
        WHERE
            CONSTRAINT_NAME = 'fk_issues_created_by'
    ) THEN
        ALTER TABLE ISSUES DROP CONSTRAINT FK_ISSUES_CREATED_BY;
        RAISE NOTICE 'Dropped constraint fk_issues_created_by';
    END IF;
END $$;
 

